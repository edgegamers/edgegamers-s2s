/** Existing callers delegate to the optional Items owner. */
import {invokeItems,invokeActorItems,spendPinnedBodyPaint} from '../core/items-provider';
import type {Body} from '../core/body-provider';
export const CompassMode={None:0,Players:1,Bodies:2} as const;
export type CompassMode=(typeof CompassMode)[keyof typeof CompassMode];
export const grantTaser=(slot:number)=>invokeActorItems(slot,(p,a)=>p.grantTaser(a),undefined);
export const grantStickers=(slot:number)=>invokeActorItems(slot,(p,a)=>p.grantStickers(a),undefined);
export const grantDnaScanner=(slot:number)=>invokeActorItems(slot,(p,a)=>p.grantDnaScanner(a),undefined);
export const grantOneShotRevolver=(slot:number)=>invokeActorItems(slot,(p,a)=>p.grantOneShotRevolver(a),undefined);
export const grantOneHitKnife=(slot:number)=>invokeActorItems(slot,(p,a)=>p.grantOneHitKnife(a),undefined);
export const grantCamo=(slot:number)=>invokeActorItems(slot,(p,a)=>p.grantCamo(a),undefined);
export const grantC4=()=>invokeItems(p=>p.grantC4(),undefined);
export const releaseC4=()=>invokeItems(p=>p.releaseC4(),undefined);
export const c4Count=()=>invokeItems(p=>p.c4Count(),0);
export const grantGloves=(slot:number,uses:number)=>invokeActorItems(slot,(p,a)=>p.grantGloves(a,uses),undefined);
export const grantBodyPaint=(slot:number,uses:number)=>invokeActorItems(slot,(p,a)=>p.grantBodyPaint(a,uses),undefined);
export const grantCompass=(slot:number,mode:CompassMode)=>invokeActorItems(slot,(p,a)=>p.grantCompass(a,mode),undefined);
export const grantTripwire=(slot:number)=>invokeActorItems(slot,(p,a)=>p.grantTripwire(a),0);
export const hasGloves=(slot:number)=>invokeActorItems(slot,(p,a)=>p.hasGloves(a),false);
export const hasBodyPaint=(slot:number)=>invokeActorItems(slot,(p,a)=>p.hasBodyPaint(a),false);
export const spendGlove=(slot:number,forBody=false)=>invokeActorItems(slot,(p,a)=>p.spendGlove(a,forBody),false);
