export const isCamouflaged=(slot:number)=>invokeActorItems(slot,(p,a)=>p.isCamouflaged(a),false);
export const placeStation=(slot:number,increment:number)=>invokeActorItems(slot,(p,a)=>p.placeStation(a,increment),false);
export const tryDefuseTripwire=(slot:number,dt:number)=>invokeActorItems(slot,(p,a)=>p.tryDefuseTripwire(a,dt),false);
export const tryPlaceHeldTripwire=(slot:number)=>invokeActorItems(slot,(p,a)=>p.tryPlaceHeldTripwire(a),false);
export const onBulletImpact=(slot:number,x:number,y:number,z:number)=>slot<0?invokeItems(p=>p.onBulletImpact(null,x,y,z),undefined):invokeActorItems(slot,(p,a)=>p.onBulletImpact(a,x,y,z),undefined);
export const tickEffects=(dt:number)=>invokeItems(p=>p.tickEffects(dt),undefined);
export const hideEffects=()=>invokeItems(p=>p.hideEffects(),undefined);
export const resetEffects=()=>invokeItems(p=>p.resetEffects(),undefined);
