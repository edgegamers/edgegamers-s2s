import {config} from '@s2script/sdk/config';
import {Server} from '@s2script/sdk/server';
import {createOwnerConfig,readValues,type OwnerConfig} from '../../../packages/contracts/config.ts';
import type {ShopSettings} from '../api';
import {SPECS} from './settings-specs';
let settings:OwnerConfig|null=null;
const FILE='_edgegamers_ttt-shop.json';
function current():OwnerConfig{if(!settings)throw Error('Shop owner settings unavailable');return settings;}
export function initializeSettings():void{
 disposeSettings();
 const initial=readValues(SPECS,s=>s.type==='bool'?config.getBool(s.path):s.type==='string'?config.getString(s.path):s.type==='int'?config.getInt(s.path):config.getFloat(s.path));
 const next=createOwnerConfig(SPECS,initial,{read:()=>config.readFile(FILE),write:text=>config.writeFile(FILE,text),
 register:s=>{if(!Server.registerCvar(s.name,{type:s.type,default:s.default,help:s.help,min:s.min,max:s.max}))throw Error('Shop alias unavailable: '+s.name);},
 getAlias:n=>Server.getCvar(n),setAlias:(n,v)=>{if(!Server.setCvar(n,v))throw Error('Shop alias mirror failed: '+n);},
 watchAlias:(n,h)=>Server.onCvarChange(n,h),log:m=>console.log(m)});
 settings=next;config.onChange(v=>next.acceptMaterialized(v));
}
export function disposeSettings():void{settings?.dispose();settings=null;}
function number(path:string):number{const v=current().roundValue(path);if(typeof v!=='number')throw Error('Expected number: '+path);return v;}
function string(path:string):string{const v=current().roundValue(path);if(typeof v!=='string')throw Error('Expected string: '+path);return v;}
function boolean(path:string):boolean{const v=current().roundValue(path);if(typeof v!=='boolean')throw Error('Expected boolean: '+path);return v;}
export function n(alias:string):number{const spec=SPECS.find(s=>s.name===alias);if(!spec)throw Error('Unknown Shop numeric alias: '+alias);return number(spec.path);}
